-- 0104_member_sign_on.sql
-- Every step of a member signing on: the invite link opened, a code asked for,
-- sent, refused or mistyped, a password tried, a login made, the welcome and
-- the tour finished. client_session (0063) only starts once she is inside
-- /me; everything before that door was unrecorded, so a member who tried and
-- failed looked exactly like a member who never tried.
-- member_id is null for an email that matched nobody -- kept, because "she
-- typed a different email" is one of the likeliest reasons a member never
-- arrives. Service-role only: RLS on with zero policies. Idempotent.

create table if not exists public.member_sign_on (
  sign_on_id    bigint generated by default as identity primary key,
  at            timestamptz not null default now(),
  member_id     uuid references public.pilot_member(member_id) on delete cascade,
  auth_user_id  uuid,
  email         text,
  step          text not null,
  ok            boolean not null default true,
  detail        text,
  device        text,
  user_agent    text,
  country       text
);
create index if not exists idx_member_sign_on_member on public.member_sign_on (member_id, at desc);
create index if not exists idx_member_sign_on_at on public.member_sign_on (at desc);
alter table public.member_sign_on enable row level security;
