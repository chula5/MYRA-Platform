-- 0105_email_click.sql
-- A member following a link in one of MYRA's emails to her: the Monday event
-- picks, the morning ways-to-wear note, a saved-piece stock alert, her
-- invitation. Every member email's links pass through /e, which writes a row
-- here and sends her on. Before this, an email that brought her back looked
-- exactly like her opening the app on her own.
-- Service-role only: RLS on with zero policies. Idempotent.

create table if not exists public.email_click (
  email_click_id  bigint generated by default as identity primary key,
  at              timestamptz not null default now(),
  member_id       uuid references public.pilot_member(member_id) on delete cascade,
  kind            text not null,
  target          text,
  device          text,
  user_agent      text,
  -- Mail scanners (Outlook Safe Links, Gmail's proxy) open links before she
  -- does. Kept, so the count can be checked, but never counted as her.
  is_bot          boolean not null default false
);
create index if not exists idx_email_click_member on public.email_click (member_id, at desc);
create index if not exists idx_email_click_at on public.email_click (at desc);
alter table public.email_click enable row level security;
